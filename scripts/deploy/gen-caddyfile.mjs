// Generates deploy/Caddyfile: HTTPS for the app at the apex <domain> (bluff.<domain> 301-redirects there) and one explicit
// host per demo storefront (normal HTTP-01 certs).
// Usage: node scripts/deploy/gen-caddyfile.mjs [--check]   (--check fails if the committed file is stale)
import fs from "node:fs";

export const STORE_SLUGS = ["fastkicks-shop", "deliveryfix-help", "tollpay-tx", "voltdeals-outlet", "cinevault-trial", "bayou-bakery", "northloop-books", "campus-tech", "lonestar-tickets", "greenleaf-grocer"];

export function caddyfile(slugs = STORE_SLUGS) {
  const stores = slugs.map((s) => `${s}.{$BASE_DOMAIN} {
\troot * /srv/stores/${s}
\tfile_server
\theader X-Robots-Tag "noindex"
}
`).join("\n");
  return `# GENERATED by scripts/deploy/gen-caddyfile.mjs: do not edit by hand.
# BASE_DOMAIN is the registered domain, e.g. "example.com": the app is https://example.com (canonical, one session cookie),
# https://bluff.example.com redirects there, and the demo stores are https://<store>.example.com.
{
\temail {$ACME_EMAIL}
}

{$BASE_DOMAIN} {
\tencode zstd gzip
\t# Server-sent events must not be buffered.
\treverse_proxy web:3000 {
\t\tflush_interval -1
\t}
}

# Old app address: keep shared links working (301 to the same path on the apex).
bluff.{$BASE_DOMAIN} {
\tredir https://{$BASE_DOMAIN}{uri} permanent
}

${stores}`;
}

if (process.argv[1] && process.argv[1].endsWith("gen-caddyfile.mjs")) {
  const out = caddyfile();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync("deploy/Caddyfile") || fs.readFileSync("deploy/Caddyfile", "utf8") !== out) { console.error("deploy/Caddyfile is stale: run node scripts/deploy/gen-caddyfile.mjs"); process.exit(1); }
    console.log("Caddyfile is up to date");
  } else { fs.mkdirSync("deploy", { recursive: true }); fs.writeFileSync("deploy/Caddyfile", out); console.log("wrote deploy/Caddyfile"); }
}
